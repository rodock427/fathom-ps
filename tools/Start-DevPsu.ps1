<#
.SYNOPSIS
    Runs PowerShell Universal in the foreground against this repo, for development. Ctrl+C stops it.
.DESCRIPTION
    Uses a PSU ZIP install (the folder holding Universal.Server) as your own user, with this repo as
    PSU's repository. By default lmstat answers come from the fake lmutil and the data generated by
    tools/New-DevData.ps1, and Active Directory from the fake. Point -LmutilPath at a real lmutil to
    poll real license servers, and add -RealDirectory to look users up in real Active Directory.

    The admin console is at http://localhost:<Port>/ and the app at /fathom. The first start asks
    you to create the admin account.
.EXAMPLE
    ./tools/Start-DevPsu.ps1 -PsuPath ~/psu
.EXAMPLE
    ./tools/Start-DevPsu.ps1 -PsuPath C:\PSU -LmutilPath 'C:\Autodesk\Network License Manager\lmutil.exe'
#>
[CmdletBinding()]
param(
    # The folder holding Universal.Server (Universal.Server.exe on Windows).
    [string] $PsuPath = $env:FATHOM_PSU_PATH,

    [string] $Dsn = ($env:LM_POSTGRES_DSN ?? 'postgresql://license_manager:license_manager@localhost:5432/license_manager'),

    # A real lmutil. Without it, the fake answers from .dev/.
    [string] $LmutilPath,

    # Look users and hosts up in real Active Directory (needs RSAT's ActiveDirectory module).
    [switch] $RealDirectory,

    [ValidateRange(1, 65535)]
    [int] $Port = 5000,

    # Listen on every network this machine is on, not just localhost. Trusted networks only.
    [switch] $Listen
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Path $PSScriptRoot -Parent
$fakes = Join-Path -Path $root -ChildPath 'tests/fakes'

$server = Join-Path -Path ([string] $PsuPath) -ChildPath ($IsWindows ? 'Universal.Server.exe' : 'Universal.Server')
if (-not $PsuPath -or -not (Test-Path -LiteralPath $server)) {
    throw "No PSU server at '$server'. Pass -PsuPath (or set FATHOM_PSU_PATH) to the folder a PSU ZIP was extracted into."
}
if (-not $IsWindows) {
    # The ZIP doesn't keep execute bits, and PSU starts its host processes from these too.
    Get-ChildItem -LiteralPath $PsuPath -Recurse -File -Include 'Universal.Server', 'PowerShellUniversal.Host' |
        ForEach-Object { chmod +x $_.FullName }
}

# A signing key that survives restarts, so sign-ins do too.
$keyFile = Join-Path -Path $HOME -ChildPath '.PowerShellUniversal/jwt.key'
if (-not (Test-Path -LiteralPath $keyFile)) {
    $null = New-Item -ItemType Directory -Path (Split-Path -Path $keyFile -Parent) -Force
    [Convert]::ToBase64String([Security.Cryptography.RandomNumberGenerator]::GetBytes(48)) | Set-Content -LiteralPath $keyFile -NoNewline
}

$settings = @{
    Kestrel__Endpoints__HTTP__Url = 'http://{0}:{1}' -f ($Listen ? '0.0.0.0' : 'localhost'), $Port
    Data__RepositoryPath          = $root
    Jwt__SigningKey               = Get-Content -LiteralPath $keyFile -Raw
    LM_POSTGRES_DSN               = $Dsn
    FATHOM_LMUTIL                 = $LmutilPath ? $LmutilPath : (Join-Path -Path $fakes -ChildPath ($IsWindows ? 'lmutil.cmd' : 'lmutil'))
    FAKE_LMUTIL_DIR               = $LmutilPath ? $null : (Join-Path -Path $root -ChildPath '.dev')
    FATHOM_AD_MODULE              = $RealDirectory ? $null : (Join-Path -Path $fakes -ChildPath 'ActiveDirectory/ActiveDirectory.psm1')
}

# Set for PSU and the jobs it starts, and put back afterwards.
$previous = @{}
foreach ($name in $settings.Keys) {
    $previous[$name] = [Environment]::GetEnvironmentVariable($name)
    [Environment]::SetEnvironmentVariable($name, $settings[$name])
}
try {
    Write-Information -MessageData "PSU on $($settings.Kestrel__Endpoints__HTTP__Url), app at /fathom. lmutil: $($settings.FATHOM_LMUTIL)" -InformationAction Continue
    & $server
} finally {
    foreach ($name in $previous.Keys) {
        [Environment]::SetEnvironmentVariable($name, $previous[$name])
    }
}
